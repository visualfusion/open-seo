import { Link } from "@tanstack/react-router";
import { ShieldAlert } from "lucide-react";
import {
  Alert,
  AlertDescription,
  AlertTitle,
} from "@/client/components/ui/alert";
import { Button } from "@/client/components/ui/button";
import { useLocale } from "@/client/lib/i18n";

/**
 * Shown when Shopify rate limited an unrendered crawl that carried a crawler
 * signature. Shopify's edge can still throttle Cloudflare Workers then, and a
 * rendered audit reads throttled pages from outside Cloudflare.
 */
export function ShopifyRateLimitAlert({
  projectId,
  startUrl,
}: {
  projectId: string;
  startUrl: string;
}) {
  const { t } = useLocale();
  return (
    <Alert variant="warning">
      <ShieldAlert />
      <AlertTitle>{t("audit.shopify.rate_limit_title")}</AlertTitle>
      <AlertDescription>{t("audit.shopify.rate_limit_desc")}</AlertDescription>
      <div className="col-start-2 mt-2">
        <Button
          variant="outline"
          size="sm"
          nativeButton={false}
          render={
            <Link
              to="/p/$projectId/audit"
              params={{ projectId }}
              search={{ url: startUrl }}
            />
          }
        >
          {t("audit.start_new_audit")}
        </Button>
      </div>
    </Alert>
  );
}
